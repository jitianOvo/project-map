def action_shortcuts(catalogs, actions=()):
    rows = []
    observed = set()
    for _key, (category, tools) in catalogs.items():
        for label, action in tools.items():
            observed.add(action)
            shortcut = action.shortcut().toString(QKeySequence.PortableText)
            if shortcut:
                rows.append((shortcut, label, category))
    for action in actions:
        if action in observed:
            continue
        shortcut = action.shortcut().toString(QKeySequence.PortableText)
        if shortcut:
            rows.append((shortcut, action.text(), "主窗口"))
    return rows


